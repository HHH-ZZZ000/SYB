"""Persistent capture task management and one-time command claiming."""

import re
import threading
import time
from datetime import datetime, timezone
from uuid import UUID, uuid4

from flask import current_app

if __package__:
    from .database import get_db, TaskConflict
else:
    from database import get_db, TaskConflict


DEVICE_PATTERN = re.compile(r"[A-Za-z0-9_-]{1,64}\Z")
TRANSITIONS = {
    "PENDING": frozenset(("SENT",)),
    "SENT": frozenset(("RUNNING", "FAILED", "TIMEOUT")),
    "RUNNING": frozenset(("SUCCESS", "FAILED", "TIMEOUT")),
    "SUCCESS": frozenset(),
    "FAILED": frozenset(),
    "TIMEOUT": frozenset(),
}


def validate_request_id(request_id):
    """Accept only the canonical UUID4 identifiers generated by this service."""
    try:
        parsed = UUID(request_id) if isinstance(request_id, str) else None
    except ValueError:
        parsed = None
    if parsed is None or parsed.version != 4 or str(parsed) != request_id:
        raise ValueError("request_id must be a canonical UUID4.")
    return request_id


def create_task(payload):
    if not isinstance(payload, dict) or not {"device", "action"} <= set(payload) or set(payload) - {"device", "action", "interaction_request_id"}:
        raise ValueError("Task body must contain exactly device and action.")
    device = payload["device"]
    if not isinstance(device, str) or not DEVICE_PATTERN.fullmatch(device):
        raise ValueError("device must contain 1-64 letters, digits, underscores or hyphens.")
    if payload["action"] not in ("capture_once", "image_capture"):
        raise ValueError("action must be capture_once or image_capture.")
    interaction = payload.get("interaction_request_id")
    if interaction is not None:
        validate_request_id(interaction)
        if payload["action"] != "image_capture":
            raise ValueError("Interaction metadata is only accepted for image tasks.")
    # Only this known display name is an alias; preserve all other device IDs.
    if device == "ESP32-S3-EYE":
        device = "ESP32_S3_EYE"
    request_id = str(uuid4())
    db = get_db()
    with db:
        db.execute("""
            INSERT INTO tasks (request_id, device, action, status, created_at, interaction_request_id)
            VALUES (?, ?, ?, 'PENDING', ?, ?)
        """, (request_id, device, payload["action"], time.time(), interaction))
    return get_task(request_id)


def get_task(request_id):
    validate_request_id(request_id)
    row = get_db().execute("SELECT * FROM tasks WHERE request_id = ?", (request_id,)).fetchone()
    if row is None:
        return None
    task = dict(row)
    if task["action"] == "image_capture":
        started = get_db().execute("SELECT started_at FROM task_running_times WHERE request_id = ?", (request_id,)).fetchone()
        task["started_at"] = started[0] if started else None
        task["image_status"] = {"PENDING": "waiting", "SENT": "waiting", "RUNNING": "capturing",
                                "SUCCESS": "success", "FAILED": "failed", "TIMEOUT": "failed"}[task["status"]]
        if task["error"] in ("camera_unavailable", "camera_clock_unavailable"):
            task["image_status"] = "unavailable"
        elif task["error"] == "image_invalid":
            task["image_status"] = "invalid"
        if task["status"] == "SUCCESS":
            result = get_db().execute("SELECT * FROM image_records WHERE id = ? AND task_id = ?",
                                      (task["result_image_id"], request_id)).fetchone()
            task["result"] = dict(result) if result else None
            if result:
                if __package__:
                    from .images import stored_image_state
                else:
                    from images import stored_image_state
                task["image_status"] = stored_image_state(result)
                task["result"]["url"] = f"/api/images/{result['id']}" if task["image_status"] == "success" else None
                task["result"]["source"] = "ESP32-S3-EYE/OV2640"
                task["result"].pop("path")
        return task
    # Keep the existing IMU API response shape unchanged.
    task.pop("result_image_id")
    task.pop("interaction_request_id")
    if task["status"] == "SUCCESS":
        # Read the associated record, never the newest periodic measurement.
        result = get_db().execute("SELECT * FROM sensor_data WHERE id = ?", (task["result_sample_id"],)).fetchone()
        task["result"] = dict(result) if result is not None else None
    return task


def device_status(request_id, payload):
    if not isinstance(payload, dict) or set(payload) - {"device", "status", "error"}:
        raise ValueError("Status body must contain device, status and optional error.")
    device = payload.get("device")
    if not isinstance(device, str) or not DEVICE_PATTERN.fullmatch(device):
        raise ValueError("Invalid device identifier.")
    if payload.get("status") not in ("RUNNING", "FAILED"):
        raise ValueError("Device may only report RUNNING or FAILED.")
    return transition_task(request_id, payload["status"], error=payload.get("error"),
                           device=device, allow_repeat=True)


def claim_command(device):
    """Atomically claim the newest pending task; SENT tasks are never resent.

    SENT records dispatch, not receipt: if the HTTP response is lost after the
    commit, this phase deliberately does not retry that task without an ACK.
    """
    if not isinstance(device, str) or not DEVICE_PATTERN.fullmatch(device):
        raise ValueError("device must contain 1-64 letters, digits, underscores or hyphens.")
    db = get_db()
    with db:
        db.execute("BEGIN IMMEDIATE")
        # Increasing IDs define creation order even if the wall clock changes.
        task = db.execute("""
            SELECT request_id, action, created_at FROM tasks
            WHERE device = ? AND status = 'PENDING' ORDER BY id DESC LIMIT 1
        """, (device,)).fetchone()
        if task is None:
            return {"command": "none"}
        db.execute("""
            UPDATE tasks SET status = 'SENT', sent_at = ?
            WHERE request_id = ? AND status = 'PENDING'
        """, (max(time.time(), task["created_at"]), task["request_id"]))
        command = {"request_id": task["request_id"], "command": task["action"]}
    # Do not return a command until its SENT update has committed successfully.
    return command


def transition_task(request_id, status, *, error=None, result_sample_id=None, device=None, allow_repeat=False):
    """Internal-only transition; callers must supply actual execution evidence.

    Device receipts may only set RUNNING/FAILED. Real success is committed by
    insert_sample(), together with a new request_id-associated measurement.
    """
    validate_request_id(request_id)
    if not isinstance(status, str) or status not in TRANSITIONS:
        raise ValueError("Unknown task status.")
    if status in ("FAILED", "TIMEOUT"):
        if not isinstance(error, str) or not error.strip() or len(error) > 1024:
            raise ValueError("Failed/timed-out tasks require an error of 1-1024 characters.")
    elif error is not None:
        raise ValueError("Only failed/timed-out tasks may have an error.")
    if status == "SUCCESS":
        if type(result_sample_id) is not int or not 1 <= result_sample_id <= 2**63 - 1:
            raise ValueError("Successful tasks require a valid result_sample_id.")
    elif result_sample_id is not None:
        raise ValueError("Only successful tasks may have a result_sample_id.")
    db = get_db()
    with db:
        # Serialize read/check/write across connections, including other app
        # instances, so competing transitions cannot overwrite a terminal state.
        db.execute("BEGIN IMMEDIATE")
        task = get_task(request_id)
        if task is None:
            raise LookupError("Task not found.")
        if device is not None and task["device"] != device:
            raise TaskConflict("Task belongs to another device.")
        if allow_repeat and status == task["status"] and error == task["error"]:
            return task
        if device is not None and task["status"] not in ("SENT", "RUNNING"):
            raise TaskConflict("Receipt requires a dispatched active task.")
        if status not in TRANSITIONS[task["status"]]:
            raise TaskConflict(f"Cannot transition {task['status']} to {status}.")
        if status == "SUCCESS":
            if task["action"] != "capture_once":
                raise ValueError("Image success requires a validated image upload.")
            sample = db.execute("SELECT device, received_at FROM sensor_data WHERE id = ?",
                                (result_sample_id,)).fetchone()
            if sample is None or sample["device"] != task["device"] or sample["received_at"] < task["sent_at"]:
                raise ValueError("Result must reference a sample from this device received after task dispatch.")
            if db.execute("SELECT 1 FROM tasks WHERE result_sample_id = ?", (result_sample_id,)).fetchone():
                raise ValueError("This sample already belongs to another task.")
        # Preserve timestamp ordering even if the server wall clock is adjusted.
        now = max(time.time(), task["created_at"], task["sent_at"] or task["created_at"])
        sent_at = now if status == "SENT" else task["sent_at"]
        finished_at = now if status in ("SUCCESS", "FAILED", "TIMEOUT") else None
        db.execute("""
            UPDATE tasks SET status = ?, sent_at = ?, finished_at = ?, error = ?, result_sample_id = ?
            WHERE request_id = ?
        """, (status, sent_at, finished_at, error, result_sample_id, request_id))
        if status == "RUNNING":
            db.execute("""
                INSERT INTO task_running_times (request_id, started_at) VALUES (?, ?)
            """, (request_id, now))
        result = get_task(request_id)
    return result


def expire_overdue_tasks(now=None):
    """Atomically expire only dispatched tasks past their own state deadline."""
    now = time.time() if now is None else now
    db = get_db()
    expired = []
    with db:
        # Competing uploads and device receipts use BEGIN IMMEDIATE too. The
        # first committed transition wins; terminal tasks are never selected.
        db.execute("BEGIN IMMEDIATE")
        candidates = db.execute("""
            SELECT t.request_id, t.status, t.sent_at, r.started_at
            FROM tasks AS t
            LEFT JOIN task_running_times AS r ON r.request_id = t.request_id
            WHERE (t.status = 'SENT' AND t.sent_at < ?)
               OR (t.status = 'RUNNING' AND COALESCE(r.started_at, t.sent_at) < ?)
        """, (now - 30, now - 60)).fetchall()
        for task in candidates:
            cursor = db.execute("""
                UPDATE tasks SET status = 'TIMEOUT', finished_at = ?, error = 'task timeout'
                WHERE request_id = ? AND status = ?
            """, (max(now, task["sent_at"]), task["request_id"], task["status"]))
            if cursor.rowcount:
                expired.append((task["request_id"], task["status"]))
    for request_id, previous in expired:
        current_app.logger.warning("Task timeout: request_id=%s %s -> TIMEOUT at=%s",
                                   request_id, previous, datetime.fromtimestamp(now, timezone.utc).isoformat())
    return expired


def start_timeout_worker(app):
    """Run the durable timeout sweep at startup and every configured interval."""
    stop = threading.Event()
    interval = app.config["TASK_TIMEOUT_CHECK_INTERVAL"]

    def run():
        while not stop.is_set():
            try:
                with app.app_context():
                    expire_overdue_tasks()
                    if app.extensions.get("image_cleanup"):
                        app.extensions["image_cleanup"]()
            except Exception:
                app.logger.exception("Task timeout check failed; next check will retry")
            stop.wait(interval)

    worker = threading.Thread(target=run, name="task_timeout_worker", daemon=True)
    app.extensions["task_timeout_worker"] = (worker, stop)
    worker.start()
